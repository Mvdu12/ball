function name(p) { return lang === "ar" ? p.nameAr : p.nameEn; }
function nat(p) { return lang === "ar" ? p.nationalityAr : p.nationalityEn; }
function club(p) { return lang === "ar" ? p.clubAr : p.clubEn; }
function wikiFor(p) {
  const primary = lang === "ar" ? p.wikiUrlAr : p.wikiUrlEn;
  const fallback = lang === "ar" ? p.wikiUrlEn : p.wikiUrlAr;
  return primary && primary.trim() ? primary : (fallback && fallback.trim() ? fallback : null);
}
function pos(p) { return p.position[lang]; }
function ach(p) { return lang === "ar" ? p.achievementsAr : p.achievementsEn; }
function clubsHist(p) { return lang === "ar" ? p.clubsHistoryAr : p.clubsHistoryEn; }

// مود الحكم: بنلف على كل اللاعيبة من غير تكرار (كوتشينة متخلّطة)، ومعاها سجل عشان الحكم يرجع للاعب اللي فات
const REF_HINT_KEYS = ["era", "nat", "pos", "ach", "more", "clubs", "current", "bio"];
let refFilter = "all";   // all | active | retired
let refDeck = [];
let refHistory = [];
let refPos = -1;

function refPool() {
  return players.filter(p => refFilter === "all" || (refFilter === "active" ? p.active : !p.active));
}

function refDraw() {
  if (refDeck.length === 0) {
    refDeck = shuffle(refPool());
    // لو الدورة اتخلصت وأول لاعب جديد هو نفس اللاعب الأخير، بنبدّله عشان مايتكررش ورا بعض
    const last = refHistory[refHistory.length - 1];
    if (last && refDeck.length > 1 && refDeck[refDeck.length - 1].id === last.id) refDeck.unshift(refDeck.pop());
  }
  return refDeck.pop();
}

function refOpenState() {
  const o = {};
  REF_HINT_KEYS.forEach(k => { o[k] = false; });
  return o;
}

function showRefPlayer(p) {
  refState = { player: p, open: refOpenState() };
  render();
}

function newRefereeRound() {
  if (refPos < refHistory.length - 1) {
    refPos++;
  } else {
    refHistory.push(refDraw());
    refPos = refHistory.length - 1;
  }
  showRefPlayer(refHistory[refPos]);
}

function prevRefereeRound() {
  if (refPos > 0) {
    refPos--;
    showRefPlayer(refHistory[refPos]);
  }
}

function setRefFilter(f) {
  refFilter = f;
  refDeck = []; refHistory = []; refPos = -1;
  newRefereeRound();
}

function toggleAllHints() {
  const hints = refBuildHints();
  const anyClosed = hints.some(h => !refState.open[h.key]);
  hints.forEach(h => { refState.open[h.key] = anyClosed; });
  render();
}

function refHintAvailable(key) {
  const p = refState.player;
  if (key === "more") return ach(p).length > 1;
  if (key === "bio") return !!(lang === "ar" ? p.bioAr : p.bioEn);
  return true;
}

