// حفظ الإعدادات (الأسماء، الوقت، عدد الأسئلة...) في متصفح اللاعب. لو التخزين مقفول (وضع خاص مثلًا) بنكمّل عادي من غير حفظ.
function savedGet(key, fallback) {
  try {
    const raw = localStorage.getItem("nogoomKora." + key);
    return raw ? JSON.parse(raw) : fallback;
  } catch (e) { return fallback; }
}
function savedSet(key, value) {
  try { localStorage.setItem("nogoomKora." + key, JSON.stringify(value)); } catch (e) { /* مفيش مشكلة */ }
}
function savedRemove(key) {
  try { localStorage.removeItem("nogoomKora." + key); } catch (e) { /* مفيش مشكلة */ }
}

let lang = "ar";
let screen = "category"; // category | referee | bank
let refState = null;

function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

